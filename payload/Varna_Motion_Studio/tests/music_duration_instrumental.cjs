const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const M=require('../js/music-engine.js');
const analysis={comp:{duration:187,workAreaStart:12,workAreaDuration:43},events:[{time:160,type:'cut',strength:90}]};
const full=M.plan(analysis,{durationMode:'comp',duration:187,maxDuration:60,style:'corporate',source:'manual'});
assert.equal(full.duration,187);
assert.deepEqual(M.segmentDurations(full.duration).map(x=>Math.round(x*1000)),[93500,93500]);
assert.equal(full.events[0].time,160);
const selected=M.plan(analysis,{durationMode:'selection',start:12,duration:43,maxDuration:60});
assert.equal(selected.duration,43);
assert.equal(selected.start,12);
assert.equal(M.plan(analysis,{durationMode:'custom',duration:80,maxDuration:21}).duration,21);
assert.equal(M.plan({comp:{duration:3}},{durationMode:'comp',duration:3}).duration,3);
assert(!M.stylePrompt(full).toLowerCase().includes('gentle piano'));
assert(/no singer.*choir.*speech/i.test(M.stylePrompt(full)));
assert.equal(M.promptGraph(full)['2'].inputs.lyrics,'[Instrumental]');assert.equal(M.minimaxGraph(full)['4'].inputs.lyrics,'');
const root=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const engine=fs.readFileSync(path.join(root,'js/music-engine.js'),'utf8');
assert(app.includes("cfg.durationMode==='custom'?Math.min(cfg.maxDuration,available):available"));
assert(app.includes("openPage('settings')"));
for(const id of ['brainMusicOpenModelSettings','brainMusicModelsFolder','brainMusicDurationRow','brainMusicMood','brainMusicEnergy','brainMusicExclude'])assert(html.includes('id="'+id+'"'));
assert(engine.includes("args.push('--disable-auto-launch')"));
console.log('PASS music engine: headless startup, model settings, instrumental conditioning and full timeline duration');
