/* ===================== READY LIBRARY: BUNDLED MEDIA SHIM =====================
   A part of the READY library was built from projects whose stills live outside
   the .aep — After Effects only ever records a path for raster footage, it never
   embeds it. Those stills now ship in assets/ready/media and are relinked right
   after the import by jsx/ready_media.jsx.

   The relink is wired directly into the panel source, but the client package
   carries main.js obfuscated and there is no readable source for that revision,
   so the call site there cannot be edited. This shim covers it: index.html loads
   this file before main.js, callR() goes through cs.evalScript, so patching
   CSInterface.prototype.evalScript catches the insert no matter which build of
   main.js is running.

   It only ever touches an expression that begins with a bare am_readyUse( call.
   A build whose main.js already wraps the call itself does not match, so the two
   can never double-apply. Any failure falls through to the untouched original.
   ============================================================================ */
(function () {
    if (typeof CSInterface !== "function") return;
    if (!CSInterface.prototype || CSInterface.prototype.amRdMediaShim) return;
    CSInterface.prototype.amRdMediaShim = true;

    var CALL = "am_readyUse(", orig = CSInterface.prototype.evalScript, extRoot = null;

    function q(p) {
        return '"' + String(p).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
    }

    CSInterface.prototype.evalScript = function (expr, cb) {
        try {
            var s = String(expr);
            if (s.indexOf(CALL) === 0) {
                if (extRoot === null) {
                    var e = "";
                    try { e = this.getSystemPath("extension") || ""; } catch (e1) {}
                    /* newer CEP builds hand back a file:/// URL here */
                    try { e = decodeURIComponent(String(e).replace(/^file:\/{2,3}/, "")); } catch (e2) {}
                    extRoot = String(e).replace(/\\/g, "/").replace(/\/+$/, "");
                }
                if (extRoot) {
                    /* strip the wrapper, keep the argument list verbatim */
                    var args = s.substring(CALL.length).replace(/\)\s*$/, "");
                    expr = '(function(){'
                         + 'if(typeof am_rdWrap!=="function"){try{$.evalFile(new File('
                         + q(extRoot + "/jsx/ready_media.jsx") + '));}catch(e){}}'
                         + 'if(typeof am_rdWrap!=="function") return am_readyUse(' + args + ');'
                         + 'return am_rdWrap(' + args + ',' + q(extRoot + "/assets/ready/media") + ');'
                         + '})()';
                }
            }
        } catch (e3) {}
        return orig.call(this, expr, cb);
    };
})();
